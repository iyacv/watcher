# build.ps1 — Builds the offline portable bundle for the client.
# Run this on YOUR machine (with internet). Produces dist\NYKFilWatcher-<date>.zip
# The client extracts that ZIP and double-clicks setup.bat. No installs needed on their side.

$ErrorActionPreference = "Stop"
$ProgressPreference    = "SilentlyContinue"

$BUILD_DIR = Split-Path -Parent $MyInvocation.MyCommand.Path
$REPO      = Split-Path -Parent $BUILD_DIR
$DOWNLOAD  = Join-Path $BUILD_DIR "downloads"
$DIST      = Join-Path $REPO "dist"
$STAGE     = Join-Path $DIST "NYKFilWatcher"

# ── Versions (pin to known-good releases) ───────────────────────────────────
$PY_VER      = "3.11.9"
$GRAFANA_VER = "11.2.2"
$PLUGIN_VER  = "3.5.0"

$PY_URL      = "https://www.python.org/ftp/python/$PY_VER/python-$PY_VER-embed-amd64.zip"
$GRAFANA_URL = "https://dl.grafana.com/oss/release/grafana-$GRAFANA_VER.windows-amd64.zip"
$PLUGIN_URL  = "https://github.com/fr-ser/grafana-sqlite-datasource/releases/download/v$PLUGIN_VER/frser-sqlite-datasource-$PLUGIN_VER.zip"
$GET_PIP_URL = "https://bootstrap.pypa.io/get-pip.py"

# ── Prep ────────────────────────────────────────────────────────────────────
New-Item -ItemType Directory -Force -Path $DOWNLOAD,$DIST | Out-Null
if (Test-Path $STAGE) { Remove-Item -Recurse -Force $STAGE }
New-Item -ItemType Directory -Force -Path $STAGE | Out-Null

function Get-IfMissing($url, $out) {
    if (Test-Path $out) {
        Write-Host "  cached: $(Split-Path -Leaf $out)"
    } else {
        Write-Host "  downloading: $url"
        Invoke-WebRequest -Uri $url -OutFile $out
    }
}

# ── 1. Python embeddable ────────────────────────────────────────────────────
Write-Host "[1/6] Python $PY_VER embeddable"
$pyZip = Join-Path $DOWNLOAD "python-$PY_VER-embed.zip"
Get-IfMissing $PY_URL $pyZip
$pyDir = Join-Path $STAGE "python"
Expand-Archive $pyZip -DestinationPath $pyDir -Force

# Enable site-packages in the embeddable distribution
$pthFile = Get-ChildItem (Join-Path $pyDir "python*._pth") | Select-Object -First 1
$lines = Get-Content $pthFile.FullName
$lines = $lines | ForEach-Object { if ($_ -match '^\s*#\s*import\s+site') { 'import site' } else { $_ } }
if ($lines -notcontains 'Lib\site-packages') { $lines += 'Lib\site-packages' }
Set-Content -Path $pthFile.FullName -Value $lines -Encoding ASCII

# Bootstrap pip into the embeddable
$getPip = Join-Path $DOWNLOAD "get-pip.py"
Get-IfMissing $GET_PIP_URL $getPip
& "$pyDir\python.exe" $getPip --no-warn-script-location | Out-Null

# ── 2. Install Python dependencies into the embeddable ──────────────────────
Write-Host "[2/6] Installing Python dependencies into bundled Python"
$reqFile = Join-Path $REPO "requirements.txt"
& "$pyDir\python.exe" -m pip install --no-warn-script-location -r $reqFile | Out-Null

# ── 3. Grafana portable ─────────────────────────────────────────────────────
Write-Host "[3/6] Grafana $GRAFANA_VER (Windows portable)"
$gfZip = Join-Path $DOWNLOAD "grafana-$GRAFANA_VER.zip"
Get-IfMissing $GRAFANA_URL $gfZip
$gfStage = Join-Path $STAGE "_grafana_extract"
Expand-Archive $gfZip -DestinationPath $gfStage -Force
$gfInner = Get-ChildItem $gfStage -Directory | Select-Object -First 1
Move-Item $gfInner.FullName (Join-Path $STAGE "grafana")
Remove-Item -Recurse -Force $gfStage

# ── 4. SQLite datasource plugin ─────────────────────────────────────────────
Write-Host "[4/6] frser-sqlite-datasource plugin v$PLUGIN_VER"
$plZip = Join-Path $DOWNLOAD "frser-sqlite-datasource-$PLUGIN_VER.zip"
Get-IfMissing $PLUGIN_URL $plZip
$pluginsDir = Join-Path $STAGE "grafana\data\plugins"
New-Item -ItemType Directory -Force $pluginsDir | Out-Null
Expand-Archive $plZip -DestinationPath $pluginsDir -Force
# Normalize plugin folder name → "frser-sqlite-datasource"
$pluginInner = Get-ChildItem $pluginsDir -Directory | Where-Object { $_.Name -ne "frser-sqlite-datasource" } | Select-Object -First 1
if ($pluginInner) {
    $target = Join-Path $pluginsDir "frser-sqlite-datasource"
    if (Test-Path $target) { Remove-Item -Recurse -Force $target }
    Move-Item $pluginInner.FullName $target
}

# ── 5. Grafana custom.ini (allow plugin, set defaults) ──────────────────────
Write-Host "[5/6] Writing Grafana custom.ini"
$customIni = @"
# Auto-generated by build.ps1 — overrides defaults.ini.
[paths]
data       = data
logs       = data/log
plugins    = data/plugins
provisioning = conf/provisioning

[server]
http_port = 3000

[security]
admin_user     = admin
admin_password = admin
allow_embedding = true

[users]
allow_sign_up = false

[plugins]
allow_loading_unsigned_plugins = frser-sqlite-datasource

[analytics]
reporting_enabled = false
check_for_updates = false
"@
$customIni | Set-Content (Join-Path $STAGE "grafana\conf\custom.ini") -Encoding ASCII

# ── 6. Copy watcher source into the bundle ──────────────────────────────────
Write-Host "[6/6] Copying watcher source"
$excludeDirs  = @("dist","build","downloads","__pycache__","processed","failed",".git",".venv",".vscode")
$excludeFiles = @("*.pyc","*.zip","*.db","*.db-journal")
$xdArgs = @()
foreach ($e in $excludeDirs) { $xdArgs += "/XD"; $xdArgs += (Join-Path $REPO $e) }
robocopy $REPO $STAGE /E /XF @excludeFiles @xdArgs /NFL /NDL /NJH /NJS /NP | Out-Null

# Empty inbox/processed/failed so the client starts clean
foreach ($d in @("inbox","processed","failed")) {
    $p = Join-Path $STAGE $d
    New-Item -ItemType Directory -Force $p | Out-Null
    Get-ChildItem $p -ErrorAction Ignore | Remove-Item -Recurse -Force
}

# ── 7. Zip ──────────────────────────────────────────────────────────────────
$stamp = Get-Date -Format "yyyyMMdd"
$out = Join-Path $DIST "NYKFilWatcher-$stamp.zip"
if (Test-Path $out) { Remove-Item $out }
Write-Host "Compressing → $out"
Compress-Archive -Path "$STAGE\*" -DestinationPath $out -CompressionLevel Optimal

$sizeMB = [math]::Round((Get-Item $out).Length / 1MB, 1)
Write-Host ""
Write-Host "═══════════════════════════════════════════════════════"
Write-Host "  Bundle ready:"
Write-Host "    $out"
Write-Host "    Size: $sizeMB MB"
Write-Host ""
Write-Host "  Client steps:"
Write-Host "    1. Extract the ZIP anywhere (e.g. C:\NYKFilWatcher)"
Write-Host "    2. Double-click setup.bat"
Write-Host "    3. Open http://localhost:3000  (admin / admin)"
Write-Host "═══════════════════════════════════════════════════════"
